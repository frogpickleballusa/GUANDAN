# Builds the single-file edge function and copies the engine into the site.
import shutil
eng=open('src/engine.js').read(); bot=open('src/bot.js').read(); core=open('src/core.js').read(); h=open('src/handler.js').read()
imp=[l for l in h.splitlines() if l.startswith('import ')]
rest='\n'.join(l for l in h.splitlines() if not l.startswith('import '))
out='// @ts-nocheck\n// Generated by build.py from src/ — edit those files, not this one.\n'+'\n'.join(imp)+'\n\n'+eng+'\n\n'+bot+'\n\n'+core+'\n\n'+rest+'\n'
open('supabase/functions/game/index.ts','w').write(out)
shutil.copy('src/engine.js','docs/engine.js')
print('built', len(out))
